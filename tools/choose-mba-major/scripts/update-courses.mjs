// Refreshes the MBA course list the tool ships with. Run it each semester,
// once the registrar has published the term's courses:
//
//   pnpm --filter @penntools/tool-choose-mba-major update-courses          # current term
//   pnpm --filter @penntools/tool-choose-mba-major update-courses 2027C    # a specific term
//
// It fetches Penn Course Plan's public course list, keeps the Wharton MBA
// courses (buildCatalog in src/courses.ts) and rewrites src/currentCatalog.ts.
// Review the diff, then commit it. This runs on a teammate's machine, never
// in the web app.

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { buildCatalog } from "../dist/courses.js";

const term = process.argv[2] ?? "current";
const url = `https://penncourseplan.com/api/base/${term}/courses/`;

console.log(`Fetching ${url}`);
const response = await fetch(url, { headers: { Accept: "application/json" } });
if (!response.ok) {
  console.error(`Penn Course Plan answered ${response.status}. Check the term code (e.g. 2027A, 2027C).`);
  process.exit(1);
}
const raw = await response.json();
if (!Array.isArray(raw) || raw.length === 0) {
  console.error("Penn Course Plan returned no courses for that term.");
  process.exit(1);
}

const semester = raw[0].semester;
const catalog = buildCatalog(raw, { term: semester, updated: new Date().toISOString().slice(0, 10) });
if (catalog.courses.length === 0) {
  console.error(`No Wharton MBA courses found for ${semester}; leaving the current list unchanged.`);
  process.exit(1);
}

const source = `// Generated by scripts/update-courses.mjs. Don't edit by hand; rerun the script.
import type { Catalog } from "./courses.js";

export const CURRENT_CATALOG: Catalog = ${JSON.stringify(catalog, null, 2)};
`;
const out = fileURLToPath(new URL("../src/currentCatalog.ts", import.meta.url));
await writeFile(out, source);

const byDepartment = {};
for (const c of catalog.courses) byDepartment[c.department] = (byDepartment[c.department] ?? 0) + 1;
console.log(`Wrote ${catalog.courses.length} courses for ${catalog.termLabel} to src/currentCatalog.ts`);
console.log(Object.entries(byDepartment).map(([d, n]) => `${d} ${n}`).join(", "));
