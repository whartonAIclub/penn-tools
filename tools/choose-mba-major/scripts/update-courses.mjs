// Rebuilds the MBA course list the tool ships with, from the Course Match
// lists saved in data/:
//
//   pnpm --filter @penntools/tool-choose-mba-major update-courses
//
// Each file data/coursematch-{term}.json is one semester's courses from Wharton
// Course Match (e.g. coursematch-2026C.json for Fall 2026), in this shape:
//
//   {
//     "term": "2026C", "label": "Fall 2026", "source": "…", "pulled": "2026-11-10",
//     "columns": ["code", "title", "credits", "sections", "sessions", "crossListed", "rating", "notes", "description"],
//     "courses": [["ACCT 6110", "Fundamentals of Financial Accounting", 1, 2, ["Full"], [], 3.14, "Cannot be taken Pass/Fail.", "…"], …]
//   }
//
// "rating" is the average of the course's sections' "3 YR Avg Course Rating"
// in Course Match, or null when none is rated. "notes" is the line Course Match
// shows under the course's title, such as "Open to 2nd year HCMG majors only";
// the tool reads "… majors only" from it. Save only course details: no
// one's bids, utilities, enrollment or schedule.
//
// The script combines every file it finds (buildCatalog in src/courses.ts)
// and rewrites src/currentCatalog.ts. To move to a new pair of semesters,
// replace the files in data/ and rerun it. Review the diff, then commit it.
// This runs on a teammate's machine, never in the web app.

import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { buildCatalog } from "../dist/courses.js";

const dataDir = fileURLToPath(new URL("../data/", import.meta.url));
const files = (await readdir(dataDir)).filter((f) => /^coursematch-\d{4}[ABC]\.json$/.test(f)).sort();
if (files.length === 0) {
  console.error("No data/coursematch-{term}.json files found.");
  process.exit(1);
}

const semesters = [];
for (const file of files) {
  const saved = JSON.parse(await readFile(dataDir + file, "utf8"));
  const courses = saved.courses.map((row) => {
    const course = Object.fromEntries(saved.columns.map((name, i) => [name, row[i]]));
    return { ...course, rating: course.rating ?? null, notes: course.notes ?? "" };
  });
  semesters.push({ term: saved.term, pulled: saved.pulled, courses });
  const rated = courses.filter((c) => c.rating !== null).length;
  console.log(`${file}: ${courses.length} courses, ${rated} rated (${saved.label})`);
}

const catalog = buildCatalog(semesters, "Wharton Course Match");
if (catalog.courses.length === 0) {
  console.error("No courses found; leaving the current list unchanged.");
  process.exit(1);
}

const source = `// Generated by scripts/update-courses.mjs from data/coursematch-*.json. Don't edit by hand; rerun the script.
import type { Catalog } from "./courses.js";

export const CURRENT_CATALOG: Catalog = ${JSON.stringify(catalog, null, 2)};
`;
const out = fileURLToPath(new URL("../src/currentCatalog.ts", import.meta.url));
await writeFile(out, source);

const byDepartment = {};
for (const c of catalog.courses) byDepartment[c.department] = (byDepartment[c.department] ?? 0) + 1;
const rated = catalog.courses.filter((c) => c.rating !== null).length;
console.log(`Wrote ${catalog.courses.length} courses (${rated} rated) for ${catalog.termLabel} to src/currentCatalog.ts`);
console.log(Object.entries(byDepartment).map(([d, n]) => `${d} ${n}`).join(", "));
