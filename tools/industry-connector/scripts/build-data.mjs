// Writes src/peopleData.ts, the people the tool searches. It uses the real
// CareerPath download (data/raw/people.json) when it exists, and otherwise the
// made-up data/sample-people.csv, so the tool builds on any machine.
// src/peopleData.ts and data/raw/ are git-ignored: real names are never committed.
// Runs before every build; the tests check the industries are valid.
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const raw = new URL("data/raw/people.json", root);

let people;
let source;
if (existsSync(raw)) {
  source = "data/raw/people.json";
  people = JSON.parse(readFileSync(raw, "utf8"));
} else {
  source = "data/sample-people.csv";
  const parse = (line) => [...line.matchAll(/("([^"]*)"|[^,]*)(,|$)/g)].slice(0, -1).map((m) => m[2] ?? m[1]);
  const [header, ...rows] = readFileSync(new URL(source, root), "utf8").trim().split("\n").map(parse);
  const col = Object.fromEntries(header.map((h, i) => [h, i]));
  const byKey = new Map();
  for (const r of rows) {
    const key = `${r[col.name]}|${r[col.grad_year]}`;
    if (!byKey.has(key)) {
      byKey.set(key, {
        name: r[col.name],
        gradYear: Number(r[col.grad_year]),
        program: r[col.program],
        isAlumni: r[col.is_alumni] === "true",
        currentEmployer: r[col.current_employer] ?? "",
        currentTitle: r[col.current_title] ?? "",
        industries: [],
      });
    }
    const p = byKey.get(key);
    if (!p.industries.includes(r[col.industry])) p.industries.push(r[col.industry]);
  }
  people = [...byKey.values()];
}

const out = people.map((p, i) => ({
  id: `p${i + 1}`,
  name: p.name,
  classYear: p.gradYear,
  program: p.program,
  isAlumni: p.isAlumni,
  currentEmployer: p.currentEmployer ?? "",
  currentTitle: p.currentTitle ?? "",
  industries: p.industries,
}));

writeFileSync(
  new URL("src/peopleData.ts", root),
  `// GENERATED by scripts/build-data.mjs from ${source}. Do not edit; git-ignored.\n// A JSON string, not an object literal: TypeScript can't check thousands of literal records.\nimport type { Person } from "./types.js";\n\nexport const PEOPLE: readonly Person[] = JSON.parse(${JSON.stringify(JSON.stringify(out))});\n`,
);
console.log(`peopleData.ts: ${out.length} people from ${source}`);
